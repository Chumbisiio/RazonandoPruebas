CREATE TABLE users_roles (
    id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL
); 

ALTER TABLE public.users_roles ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.users_roles_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.courses_subjects_teachers (
    id BIGINT NOT NULL,
    courses_subjects_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL
);

ALTER TABLE public.courses_subjects_teachers ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.courses_subjects_teachers_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

-- Eliminar las claves foráneas existentes
ALTER TABLE public.users
    DROP CONSTRAINT IF EXISTS users_rol_id_fkey;

ALTER TABLE public.subjects
    DROP CONSTRAINT IF EXISTS subjects_teacher_id_fkey,
    DROP COLUMN IF EXISTS teacher_id;


-- Volver a crear las claves foráneas con las tablas nuevas y agregar restricciones de unicidad
ALTER TABLE public.users_roles
    ADD CONSTRAINT users_roles_fkey PRIMARY KEY (id),
    ADD CONSTRAINT users_roles_user_id_fkey 
    FOREIGN KEY (user_id) REFERENCES public.users(id) DEFERRABLE,
    ADD CONSTRAINT users_roles_role_id_fkey 
    FOREIGN KEY (role_id) REFERENCES public.roles(id) DEFERRABLE,
    ADD CONSTRAINT unique_users_roles UNIQUE (user_id, role_id);

ALTER TABLE public.courses_subjects_teachers
    ADD CONSTRAINT courses_subjects_teachers_fkey PRIMARY KEY (id),
    ADD CONSTRAINT courses_subjects_teachers_courses_subjects_id_fkey 
    FOREIGN KEY (courses_subjects_id) REFERENCES public.courses_subjects(id) DEFERRABLE,
    ADD CONSTRAINT courses_subjects_teachers_teachers_id_fkey 
    FOREIGN KEY (teacher_id) REFERENCES public.users(id) DEFERRABLE,
    ADD CONSTRAINT unique_courses_subjects_teachers UNIQUE (courses_subjects_id, teacher_id);

-- Agregar restricciones de unicidad a las tablas intermedias existentes
ALTER TABLE public.users_courses
   ADD CONSTRAINT unique_users_courses UNIQUE (student_id, course_id);

ALTER TABLE public.courses_subjects
    ADD CONSTRAINT unique_courses_subjects UNIQUE (course_id, subject_id);